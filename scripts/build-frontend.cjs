'use strict';

// Keep the desktop and web entry point identical while maintaining feature-sized source files.
// No framework, package installation, or runtime module loader is required.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const projectRoot = path.resolve(__dirname, '..');

function sourceFile(frontendRoot, relativePath) {
  if (typeof relativePath !== 'string' || !relativePath || path.isAbsolute(relativePath)) {
    throw new Error('Frontend source path must be relative.');
  }
  const file = path.resolve(frontendRoot, relativePath);
  if (!file.startsWith(frontendRoot + path.sep)) throw new Error('Frontend source path escapes its directory.');
  return fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trimEnd();
}

function replaceSlot(html, slot, contents) {
  const marker = '<!-- @' + slot + ' -->';
  if (html.split(marker).length !== 2) throw new Error('Expected exactly one frontend slot: ' + slot);
  return html.replace(marker, () => contents);
}

function compileFrontend(root = projectRoot) {
  const frontendRoot = path.resolve(root, 'frontend');
  const manifest = JSON.parse(sourceFile(frontendRoot, 'manifest.json'));
  for (const key of ['styles', 'scripts']) {
    if (!Array.isArray(manifest[key]) || !manifest[key].length) throw new Error('Missing frontend ' + key + ' manifest.');
    if (new Set(manifest[key]).size !== manifest[key].length) throw new Error('Duplicate frontend ' + key + ' entry.');
  }
  const styles = manifest.styles.map(file => sourceFile(frontendRoot, file)).join('\n\n');
  const scripts = manifest.scripts.map(file => sourceFile(frontendRoot, file)).join('\n\n');
  // Validate the complete shared lexical scope before replacing a working build.
  new vm.Script(scripts, {filename: 'frontend.bundle.js'});
  let html = sourceFile(frontendRoot, 'shell.html');
  for (const name of ['workspace', 'utilities', 'dialogs']) {
    html = replaceSlot(html, 'component ' + name, sourceFile(frontendRoot, 'components/' + name + '.html'));
  }
  html = replaceSlot(html, 'styles', styles);
  html = replaceSlot(html, 'scripts', scripts);
  if (/<!-- @[^>]+ -->/.test(html)) throw new Error('Unresolved frontend template slot.');
  return html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by scripts/build-frontend.cjs. Edit frontend/ source files. -->') + '\n';
}

function buildFrontend({root = projectRoot, check = false} = {}) {
  const html = compileFrontend(root);
  const output = path.resolve(root, 'index.html');
  const existing = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
  const changed = existing !== html;
  if (check && changed) throw new Error('index.html is stale. Run node scripts/build-frontend.cjs.');
  if (changed && !check) {
    const temporary = output + '.build-' + process.pid + '.tmp';
    try {
      fs.writeFileSync(temporary, html, 'utf8');
      fs.renameSync(temporary, output);
    } finally {
      if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
    }
  }
  return {html, changed, output};
}

module.exports = {compileFrontend, buildFrontend};
if (require.main === module) {
  try {
    const result = buildFrontend({check: process.argv.includes('--check')});
    console.log('Frontend ' + (result.changed ? 'built' : 'up to date') + ': ' + result.output);
  } catch (error) {
    console.error('Frontend build failed: ' + error.message);
    process.exitCode = 1;
  }
}
